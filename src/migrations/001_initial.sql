CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL,
  username_key TEXT NOT NULL UNIQUE,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  avatar_key TEXT,
  phone_number TEXT UNIQUE,
  phone_verified_at TEXT,
  theme TEXT NOT NULL DEFAULT 'light',
  read_receipts INTEGER NOT NULL DEFAULT 1 CHECK (read_receipts IN (0, 1)),
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);
CREATE TABLE connections (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_low INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  user_high INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  requester_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  recipient_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  status TEXT NOT NULL CHECK (status IN ('pending', 'accepted')),
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
  CHECK (user_low < user_high),
  CHECK (requester_id != recipient_id),
  UNIQUE (user_low, user_high)
);
CREATE TABLE messages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  recipient_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  body TEXT NOT NULL CHECK (length(body) <= 4000 AND (length(body) > 0 OR media_key IS NOT NULL)),
  media_key TEXT,
  media_type TEXT CHECK (media_type IS NULL OR media_type IN ('image', 'voice')),
  media_mime TEXT,
  media_duration REAL,
  delivered_at TEXT,
  read_at TEXT,
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
  CHECK (sender_id != recipient_id),
  CHECK (
    (media_key IS NULL AND media_type IS NULL AND media_mime IS NULL)
    OR (media_key IS NOT NULL AND media_type IS NOT NULL
      AND media_mime IN ('image/webp', 'audio/webm', 'audio/ogg', 'audio/wav', 'audio/mpeg', 'audio/mp4'))
  )
);
CREATE TABLE statuses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  body TEXT NOT NULL CHECK (length(body) <= 500 AND (length(body) > 0 OR media_key IS NOT NULL)),
  media_key TEXT,
  media_mime TEXT,
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  CHECK ((media_key IS NULL AND media_mime IS NULL) OR (media_key IS NOT NULL AND media_mime = 'image/webp'))
);
CREATE TABLE status_views (
  status_id INTEGER NOT NULL REFERENCES statuses(id) ON DELETE CASCADE,
  viewer_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  viewed_at TEXT NOT NULL,
  PRIMARY KEY (status_id, viewer_id)
);
CREATE TABLE sessions (sid TEXT PRIMARY KEY, sess TEXT NOT NULL, expires_at BIGINT NOT NULL);
CREATE TABLE login_attempts (
  ip_key TEXT PRIMARY KEY,
  window_started_at BIGINT NOT NULL,
  attempt_count INTEGER NOT NULL
);
CREATE TABLE phone_verifications (
  phone_number TEXT NOT NULL,
  purpose TEXT NOT NULL CHECK (purpose IN ('register', 'change_phone')),
  code_hash TEXT NOT NULL,
  expires_at BIGINT NOT NULL,
  attempt_count INTEGER NOT NULL,
  window_started_at BIGINT NOT NULL,
  send_count INTEGER NOT NULL,
  last_sent_at BIGINT NOT NULL,
  PRIMARY KEY (phone_number, purpose)
);
CREATE TABLE calls (
  id TEXT PRIMARY KEY,
  caller_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  recipient_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  call_type TEXT NOT NULL CHECK (call_type IN ('voice', 'video')),
  status TEXT NOT NULL CHECK (status IN ('ringing', 'connecting', 'connected', 'declined', 'missed', 'ended', 'connection_error')),
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
  answered_at TEXT,
  connected_at TEXT,
  ended_at TEXT,
  duration_seconds INTEGER NOT NULL DEFAULT 0 CHECK (duration_seconds >= 0),
  CHECK (caller_id != recipient_id)
);
CREATE TABLE call_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  call_id TEXT NOT NULL REFERENCES calls(id) ON DELETE CASCADE,
  sender_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('state', 'offer', 'answer', 'ice')),
  payload TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);
CREATE TABLE user_presence (
  user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  last_seen_at BIGINT NOT NULL
);
CREATE INDEX sessions_expiry_idx ON sessions(expires_at);
CREATE INDEX phone_verification_expiry_idx ON phone_verifications(expires_at);
CREATE INDEX calls_participants_idx ON calls(caller_id, recipient_id, status, created_at);
CREATE INDEX call_events_call_idx ON call_events(call_id, id);
CREATE INDEX call_events_sender_idx ON call_events(sender_id, id);
CREATE INDEX messages_conversation_idx ON messages(sender_id, recipient_id, id);
CREATE UNIQUE INDEX users_phone_unique_idx ON users(phone_number) WHERE phone_number IS NOT NULL;
CREATE INDEX messages_delivery_idx ON messages(recipient_id, delivered_at, read_at);
CREATE INDEX statuses_expiry_idx ON statuses(expires_at, user_id);
CREATE INDEX status_views_viewer_idx ON status_views(viewer_id, status_id);
